create or replace function public.ensure_sariscan_user()
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_name text := coalesce(
    nullif(auth.jwt() -> 'user_metadata' ->> 'display_name', ''), 'Store Owner');
  v_user_id bigint;
begin
  if v_auth_user_id is null then raise exception 'Authentication is required'; end if;
  select user_id into v_user_id from public.users
    where auth_user_id = v_auth_user_id;
  if v_user_id is null and v_email <> '' then
    update public.users set auth_user_id = v_auth_user_id, full_name = v_name
      where lower(username) = v_email and auth_user_id is null
      returning user_id into v_user_id;
  end if;
  if v_user_id is null then
    insert into public.users
      (username, password_hash, full_name, role, auth_user_id)
    values (coalesce(nullif(v_email, ''), v_auth_user_id::text), null,
      v_name, 'owner', v_auth_user_id)
    returning user_id into v_user_id;
  end if;
  return v_user_id;
end;
$$;

create or replace function public.handle_new_sariscan_auth_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_username text := lower(coalesce(new.email, new.id::text));
  v_name text := coalesce(
    nullif(new.raw_user_meta_data ->> 'display_name', ''), 'Store Owner');
begin
  update public.users set auth_user_id = new.id, full_name = v_name
    where lower(username) = v_username and auth_user_id is null;
  if not found then
    insert into public.users
      (username, password_hash, full_name, role, auth_user_id)
    values (v_username, null, v_name, 'owner', new.id)
    on conflict (auth_user_id) do update set full_name = excluded.full_name;
  end if;
  return new;
end;
$$;
drop trigger if exists on_sariscan_user_created on auth.users;
create trigger on_sariscan_user_created after insert on auth.users
  for each row execute procedure public.handle_new_sariscan_auth_user();

create or replace function public.upsert_sariscan_product(
  p_app_id text, p_name text, p_category text, p_price numeric,
  p_stock integer, p_barcode text, p_low_stock_threshold integer,
  p_is_archived boolean
) returns void language plpgsql security definer set search_path = '' as $$
declare
  v_user_id bigint := public.ensure_sariscan_user();
  v_category_id bigint;
  v_category_name text := coalesce(nullif(trim(p_category), ''), 'General');
begin
  if nullif(trim(p_app_id), '') is null or nullif(trim(p_name), '') is null
      or p_price <= 0 or p_stock < 0 or p_low_stock_threshold < 0 then
    raise exception 'Invalid product data';
  end if;
  select category_id into v_category_id from public.categories
    where user_id = v_user_id and lower(category_name) = lower(v_category_name);
  if v_category_id is null then
    begin
      insert into public.categories (user_id, category_name)
        values (v_user_id, v_category_name)
        returning category_id into v_category_id;
    exception when unique_violation then
      select category_id into v_category_id from public.categories
        where user_id = v_user_id and lower(category_name) = lower(v_category_name);
    end;
  end if;
  insert into public.products
    (user_id, app_id, product_name, barcode, category_id, unit_price,
     stock_quantity, low_stock_threshold, is_archived)
  values (v_user_id, trim(p_app_id), trim(p_name), nullif(trim(p_barcode), ''),
    v_category_id, p_price, p_stock, p_low_stock_threshold, p_is_archived)
  on conflict (user_id, app_id) do update set
    product_name = excluded.product_name, barcode = excluded.barcode,
    category_id = excluded.category_id, unit_price = excluded.unit_price,
    stock_quantity = excluded.stock_quantity,
    low_stock_threshold = excluded.low_stock_threshold,
    is_archived = excluded.is_archived;
end;
$$;

create or replace function public.upsert_sariscan_customer(
  p_app_id text, p_name text, p_phone text
) returns void language plpgsql security definer set search_path = '' as $$
declare v_user_id bigint := public.ensure_sariscan_user();
begin
  if nullif(trim(p_app_id), '') is null or nullif(trim(p_name), '') is null then
    raise exception 'Invalid customer data';
  end if;
  insert into public.customers (user_id, app_id, full_name, contact_number)
  values (v_user_id, trim(p_app_id), trim(p_name), nullif(trim(p_phone), ''))
  on conflict (user_id, app_id) do update set
    full_name = excluded.full_name, contact_number = excluded.contact_number;
end;
$$;

create or replace function public.record_sariscan_payment(
  p_app_id text, p_customer_app_id text, p_amount numeric,
  p_entry_date timestamptz, p_note text
) returns void language plpgsql security definer set search_path = '' as $$
declare
  v_user_id bigint := public.ensure_sariscan_user();
  v_customer_id bigint;
  v_balance numeric(10, 2);
begin
  select customer_id into v_customer_id from public.customers
    where user_id = v_user_id and app_id = p_customer_app_id;
  if v_customer_id is null then
    raise exception 'Customer does not belong to the signed-in shop';
  end if;
  select coalesce(sum(case when entry_type = 'credit' then amount else -amount end), 0)
    into v_balance from public.utang_ledger where customer_id = v_customer_id;
  if p_amount <= 0 or p_amount > v_balance then
    raise exception 'Payment must be greater than zero and no more than the balance';
  end if;
  insert into public.utang_ledger
    (customer_id, transaction_id, entry_type, amount, balance_after,
     entry_date, app_id, note)
  values (v_customer_id, null, 'payment', p_amount, v_balance - p_amount,
    coalesce(p_entry_date, now()), p_app_id,
    coalesce(nullif(trim(p_note), ''), 'Customer payment'))
  on conflict (customer_id, app_id) do nothing;
end;
$$;

create or replace function public.save_sariscan_sale(
  p_sale jsonb, p_items jsonb, p_ledger jsonb default null
) returns void language plpgsql security definer set search_path = '' as $$
declare
  v_user_id bigint := public.ensure_sariscan_user();
  v_customer_id bigint;
  v_transaction_id bigint;
  v_product_id bigint;
  v_item jsonb;
  v_quantity integer;
  v_total numeric(10, 2) := (p_sale ->> 'total')::numeric;
  v_received numeric(10, 2) := (p_sale ->> 'amount_received')::numeric;
  v_change numeric(10, 2) := (p_sale ->> 'change_amount')::numeric;
  v_payment_type text := p_sale ->> 'payment_type';
  v_items_total numeric(10, 2) := 0;
  v_balance numeric(10, 2);
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'A sale must contain at least one item';
  end if;
  if v_total < 0 or v_payment_type not in ('cash', 'utang') then
    raise exception 'Invalid sale data';
  end if;
  if v_payment_type = 'cash'
      and (v_received < v_total or v_change <> v_received - v_total) then
    raise exception 'Cash totals do not balance';
  end if;
  if v_payment_type = 'utang' and (v_received <> 0 or v_change <> 0) then
    raise exception 'Utang sales cannot contain cash or change';
  end if;
  if nullif(p_sale ->> 'customer_id', '') is not null then
    select customer_id into v_customer_id from public.customers
      where user_id = v_user_id and app_id = p_sale ->> 'customer_id';
    if v_customer_id is null then
      raise exception 'Customer does not belong to the signed-in shop';
    end if;
  end if;
  if v_payment_type = 'utang' and v_customer_id is null then
    raise exception 'An utang sale requires a customer';
  end if;
  insert into public.transactions
    (receipt_number, user_id, customer_id, transaction_date, total_amount,
     amount_received, change_amount, payment_type, status)
  values (p_sale ->> 'id', v_user_id, v_customer_id,
    (p_sale ->> 'created_at')::timestamptz, v_total, v_received, v_change,
    v_payment_type, 'completed')
  on conflict (user_id, receipt_number) do nothing
  returning transaction_id into v_transaction_id;
  if v_transaction_id is null then return; end if;

  for v_item in select value from jsonb_array_elements(p_items) loop
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity <= 0 then
      raise exception 'Sale item quantity must be greater than zero';
    end if;
    select product_id into v_product_id from public.products
      where user_id = v_user_id and app_id = v_item ->> 'product_id'
        and not is_archived;
    if v_product_id is null then
      raise exception 'A sale product does not belong to the signed-in shop';
    end if;
    update public.products set stock_quantity = stock_quantity - v_quantity
      where product_id = v_product_id and stock_quantity >= v_quantity;
    if not found then
      raise exception 'Insufficient database stock for a sale item';
    end if;
    insert into public.transaction_items
      (transaction_id, product_id, quantity, unit_price, subtotal)
    values (v_transaction_id, v_product_id, v_quantity,
      (v_item ->> 'unit_price')::numeric,
      v_quantity * (v_item ->> 'unit_price')::numeric);
    v_items_total := v_items_total
      + v_quantity * (v_item ->> 'unit_price')::numeric;
  end loop;
  if v_items_total <> v_total then
    raise exception 'Sale header total does not match its items';
  end if;

  if v_payment_type = 'utang' then
    if p_ledger is null then raise exception 'An utang sale requires a ledger entry'; end if;
    select coalesce(sum(case when entry_type = 'credit' then amount else -amount end), 0)
      into v_balance from public.utang_ledger where customer_id = v_customer_id;
    insert into public.utang_ledger
      (customer_id, transaction_id, entry_type, amount, balance_after,
       entry_date, app_id, note)
    values (v_customer_id, v_transaction_id, 'credit', v_total,
      v_balance + v_total, (p_ledger ->> 'created_at')::timestamptz,
      p_ledger ->> 'id',
      coalesce(nullif(p_ledger ->> 'note', ''), 'Utang sale'));
  end if;
end;
$$;

