-- SariScan schema for the existing Supabase tables.
-- Keeps supplied bigint keys and normalized relations, adds Auth ownership and
-- stable app IDs. Legacy rows stay intact and unassigned instead of being
-- silently attached to the wrong shop.

create table if not exists public.users (
  user_id bigint generated by default as identity primary key,
  username varchar(255) not null unique,
  password_hash varchar(255),
  full_name varchar(60) not null,
  role varchar(20) not null default 'owner',
  auth_user_id uuid references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.categories (
  category_id bigint generated by default as identity primary key,
  category_name varchar(50) not null,
  description varchar(150),
  user_id bigint references public.users(user_id) on delete cascade
);
create table if not exists public.customers (
  customer_id bigint generated by default as identity primary key,
  full_name varchar(60) not null,
  contact_number varchar(20),
  created_at timestamptz not null default now(),
  user_id bigint references public.users(user_id) on delete cascade,
  app_id varchar(20)
);
create table if not exists public.products (
  product_id bigint generated by default as identity primary key,
  product_name varchar(60) not null,
  barcode varchar(30),
  category_id bigint references public.categories(category_id)
    on update cascade on delete set null,
  unit_price numeric(10, 2) not null default 0 check (unit_price >= 0),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  low_stock_threshold integer not null default 0
    check (low_stock_threshold >= 0),
  created_at timestamptz not null default now(),
  user_id bigint references public.users(user_id) on delete cascade,
  app_id varchar(20),
  is_archived boolean not null default false
);
create table if not exists public.transactions (
  transaction_id bigint generated by default as identity primary key,
  receipt_number varchar(20) not null,
  user_id bigint not null references public.users(user_id)
    on update cascade on delete restrict,
  customer_id bigint references public.customers(customer_id)
    on update cascade on delete set null,
  transaction_date timestamptz not null default now(),
  total_amount numeric(10, 2) not null default 0 check (total_amount >= 0),
  amount_received numeric(10, 2) not null default 0
    check (amount_received >= 0),
  change_amount numeric(10, 2) not null default 0
    check (change_amount >= 0),
  payment_type varchar(10) not null,
  status varchar(15) not null default 'completed'
);
create table if not exists public.transaction_items (
  transaction_item_id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.transactions(transaction_id)
    on update cascade on delete cascade,
  product_id bigint not null references public.products(product_id)
    on update cascade on delete restrict,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10, 2) not null check (unit_price >= 0),
  subtotal numeric(10, 2) not null check (subtotal >= 0)
);
create table if not exists public.utang_ledger (
  ledger_id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(customer_id)
    on update cascade on delete restrict,
  transaction_id bigint references public.transactions(transaction_id)
    on update cascade on delete set null,
  entry_type varchar(10) not null,
  amount numeric(10, 2) not null check (amount >= 0),
  balance_after numeric(10, 2) not null,
  entry_date timestamptz not null default now(),
  app_id varchar(20),
  note varchar(150) not null default ''
);

